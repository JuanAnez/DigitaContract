-- ======================================================================
-- 1. ELIMINAR TABLAS EXISTENTES (si existen)
-- ======================================================================
DROP TABLE IC_ADMIN.DELIVERY_EVENTS CASCADE CONSTRAINTS;
DROP TABLE IC_ADMIN.CONTRACT_AUDIT_LOG CASCADE CONSTRAINTS;
DROP TABLE IC_ADMIN.CONTRACT_PARTIES CASCADE CONSTRAINTS;
DROP TABLE IC_ADMIN.CONTRACTS CASCADE CONSTRAINTS;

-- ======================================================================
-- 2. CREAR TABLA CONTRACTS
-- ======================================================================
CREATE TABLE IC_ADMIN.CONTRACTS (
  ID                   NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  CONTRACT_UID         VARCHAR2(64) NOT NULL,
  CONTRACT_TYPE        VARCHAR2(50) NOT NULL,
  ACCOUNT_TYPE         VARCHAR2(50),
  BAN_NUMBER           VARCHAR2(50),
  SUBSCRIBER_NUMBER    VARCHAR2(50),
  SOURCE_SYSTEM        VARCHAR2(10),
  EXTERNAL_ID          VARCHAR2(128),
  TEMPLATE_ID          VARCHAR2(64) NOT NULL,
  VERSION              NUMBER(10) DEFAULT 1 NOT NULL,
  STATUS               VARCHAR2(30) DEFAULT 'DRAFT' NOT NULL,
  STATUS_MESSAGE       VARCHAR2(4000),
  FILE_URI             VARCHAR2(1024) NOT NULL,
  FILE_SHA256          VARCHAR2(64) NOT NULL,
  SIGNED_PDF_URI       VARCHAR2(1024),
  SIGNED_PDF_SHA256    VARCHAR2(64),
  CUSTOMER_SIGNED_AT   TIMESTAMP WITH TIME ZONE,
  AGENT_SIGNED_AT      TIMESTAMP WITH TIME ZONE,
  CREATED_BY_USER_ID   VARCHAR2(64),
  CREATED_AT           TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  UPDATED_AT           TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL
);

-- ======================================================================
-- 3. CREAR TABLA CONTRACT_PARTIES
-- ======================================================================
CREATE TABLE IC_ADMIN.CONTRACT_PARTIES (
  ID            NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  CONTRACT_ID   NUMBER(19) NOT NULL,
  ROLE          VARCHAR2(20) NOT NULL,
  FULL_NAME     VARCHAR2(200) NOT NULL,
  EMAIL         VARCHAR2(200),
  PHONE         VARCHAR2(50),
  CREATED_AT    TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL
);

-- ======================================================================
-- 4. CREAR TABLA CONTRACT_AUDIT_LOG
-- ======================================================================
CREATE TABLE IC_ADMIN.CONTRACT_AUDIT_LOG (
  ID             NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  CONTRACT_ID    NUMBER(19) NOT NULL,
  ACTOR_USER_ID  VARCHAR2(64),
  ACTION         VARCHAR2(50) NOT NULL,
  STATUS         VARCHAR2(50),
  MESSAGE        VARCHAR2(2000),
  AT             TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL
);

-- ======================================================================
-- 5. CREAR TABLA DELIVERY_EVENTS
-- ======================================================================
CREATE TABLE IC_ADMIN.DELIVERY_EVENTS (
  ID              NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  CONTRACT_ID     NUMBER(19) NOT NULL,
  CHANNEL         VARCHAR2(10) NOT NULL,
  ADDRESS         VARCHAR2(320) NOT NULL,
  STATUS          VARCHAR2(10) NOT NULL,
  PROVIDER_MSG_ID VARCHAR2(128),
  ERROR_MESSAGE   VARCHAR2(2000),
  SENT_AT         TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL
);

-- ======================================================================
-- 6. CREAR ÍNDICES
-- ======================================================================
CREATE INDEX IX_CONTRACTS_LOOKUP     ON IC_ADMIN.CONTRACTS (CONTRACT_UID, BAN_NUMBER, SUBSCRIBER_NUMBER);
CREATE INDEX IX_CONTRACTS_STATUS     ON IC_ADMIN.CONTRACTS (STATUS);
CREATE INDEX IX_CONTRACTS_CREATED_AT ON IC_ADMIN.CONTRACTS (CREATED_AT);

CREATE UNIQUE INDEX UQ_PARTY_PER_ROLE ON IC_ADMIN.CONTRACT_PARTIES (CONTRACT_ID, ROLE);
CREATE INDEX IX_PARTIES_CONTRACT      ON IC_ADMIN.CONTRACT_PARTIES (CONTRACT_ID);

CREATE INDEX IX_AUDIT_CONTRACT ON IC_ADMIN.CONTRACT_AUDIT_LOG (CONTRACT_ID);
CREATE INDEX IX_AUDIT_AT       ON IC_ADMIN.CONTRACT_AUDIT_LOG (AT DESC);

CREATE INDEX IX_DELIVERY_CONTRACT ON IC_ADMIN.DELIVERY_EVENTS (CONTRACT_ID);
CREATE INDEX IX_DELIVERY_AT       ON IC_ADMIN.DELIVERY_EVENTS (SENT_AT DESC);

-- ======================================================================
-- 7. CREAR FOREIGN KEYS
-- ======================================================================
ALTER TABLE IC_ADMIN.CONTRACT_PARTIES ADD CONSTRAINT FK_PARTIES_CONTRACT 
  FOREIGN KEY (CONTRACT_ID) REFERENCES IC_ADMIN.CONTRACTS(ID) ON DELETE CASCADE;

ALTER TABLE IC_ADMIN.CONTRACT_AUDIT_LOG ADD CONSTRAINT FK_AUDIT_CONTRACT 
  FOREIGN KEY (CONTRACT_ID) REFERENCES IC_ADMIN.CONTRACTS(ID) ON DELETE CASCADE;

ALTER TABLE IC_ADMIN.DELIVERY_EVENTS ADD CONSTRAINT FK_DELIVERY_CONTRACT 
  FOREIGN KEY (CONTRACT_ID) REFERENCES IC_ADMIN.CONTRACTS(ID) ON DELETE CASCADE;

-- ======================================================================
-- 8. GRANTS
-- ======================================================================
